#!/bin/bash

set -e

BUILD_SCRIPT="$HOME/weekly-build.sh"
RUNNING_FILE="$HOME/.weekly-build.running"


# ============================================================
# 记录当前编译进程 PID
# ============================================================

echo "$$" > "$RUNNING_FILE"


# ============================================================
# 无论正常结束、失败、终止，都清理运行状态
# ============================================================

cleanup() {
    rm -f "$RUNNING_FILE"
}

trap cleanup EXIT INT TERM


# ============================================================
# 开始执行编译
# ============================================================

echo
echo "============================================================"
echo "ImmortalWrt 自动编译开始"
echo "开始时间：$(date '+%Y-%m-%d %H:%M:%S')"
echo "PID：$$"
echo "============================================================"
echo


# ============================================================
# 执行真正的编译脚本
# ============================================================

bash "$BUILD_SCRIPT"

RESULT=$?


# ============================================================
# 编译结果
# ============================================================

echo
echo "============================================================"

if [ "$RESULT" -eq 0 ]; then
    echo "ImmortalWrt 编译成功"
else
    echo "ImmortalWrt 编译失败"
    echo "退出代码：$RESULT"
fi

echo "结束时间：$(date '+%Y-%m-%d %H:%M:%S')"
echo "============================================================"

exit "$RESULT"
